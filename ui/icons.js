window.pixelIcon = function (name) {
  const rows = window.PIXEL_ICONS[name];
  if (!rows) return "";
  const h = rows.length, w = rows[0].length;
  let rects = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === "#") {
        let run = 1;
        while (row[x + run] === "#") run++;
        rects += `<rect x="${x}" y="${y}" width="${run}" height="1"/>`;
        x += run - 1;
      }
    }
  });
  return `<svg viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`;
};

window.renderIcons = function (root = document) {
  root.querySelectorAll("i[data-icon]").forEach((el) => {
    if (!el.dataset.done) {
      el.innerHTML = window.pixelIcon(el.dataset.icon);
      el.dataset.done = "1";
    }
  });
};
